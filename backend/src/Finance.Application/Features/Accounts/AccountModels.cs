using Finance.Application.Common;
using Finance.Domain.Accounts;
using FluentValidation;

namespace Finance.Application.Features.Accounts;

/// <summary>Writable account fields; shared by REST and sync.</summary>
public record AccountPayload
{
    public string? Name { get; init; }

    public AccountType? Type { get; init; }

    public string? Currency { get; init; }

    /// <summary>Minor units of the account currency.</summary>
    public long InitialBalance { get; init; }

    public bool IncludeInTotals { get; init; } = true;

    public bool IsArchived { get; init; }

    public int SortOrder { get; init; }

    public string? Color { get; init; }

    public string? Icon { get; init; }

    /// <summary>CreditCard only. Minor units.</summary>
    public long? CreditLimit { get; init; }

    /// <summary>Deposit/Savings only. Annual rate, percent.</summary>
    public decimal? InterestRatePercent { get; init; }

    public CapitalizationPeriod? CapitalizationPeriod { get; init; }

    public DateOnly? OpenDate { get; init; }

    public DateOnly? MaturityDate { get; init; }
}

public sealed record CreateAccountRequest : AccountPayload
{
    /// <summary>Client-generated UUID v7. Generated by the server when omitted.</summary>
    public Guid? Id { get; init; }
}

public sealed record AccountResponse(
    Guid Id,
    string Name,
    AccountType Type,
    string Currency,
    long InitialBalance,
    long Balance,
    bool IncludeInTotals,
    bool IsArchived,
    int SortOrder,
    string? Color,
    string? Icon,
    long? CreditLimit,
    decimal? InterestRatePercent,
    CapitalizationPeriod? CapitalizationPeriod,
    DateOnly? OpenDate,
    DateOnly? MaturityDate,
    long Version,
    DateTime CreatedAt,
    DateTime UpdatedAt)
{
    public static AccountResponse From(Account a, long balance) => new(
        a.Id, a.Name, a.Type, a.Currency, a.InitialBalance, balance, a.IncludeInTotals, a.IsArchived, a.SortOrder,
        a.Color, a.Icon, a.CreditLimit, a.InterestRatePercent, a.CapitalizationPeriod, a.OpenDate, a.MaturityDate,
        a.Version, a.CreatedAt, a.UpdatedAt);
}

public sealed record AccountBalanceInBase(Guid AccountId, MoneyDto Balance, MoneyDto BalanceInBase);

/// <summary>Total capital of accounts with IncludeInTotals, converted to the base currency at the latest rate.</summary>
public sealed record AccountsSummaryResponse(MoneyDto Total, DateOnly RatesDate, IReadOnlyList<AccountBalanceInBase> Accounts);

internal sealed class AccountPayloadValidator : AbstractValidator<AccountPayload>
{
    public AccountPayloadValidator()
    {
        RuleFor(x => x.Name).NotEmpty().MaximumLength(100);
        RuleFor(x => x.Type).NotNull().IsInEnum();
        RuleFor(x => x.Currency).NotEmpty().IsCurrencyCode();
        RuleFor(x => x.Color).IsHexColor();
        RuleFor(x => x.Icon).MaximumLength(50);
        RuleFor(x => x.OpenDate).IsSaneDate();
        RuleFor(x => x.MaturityDate).IsSaneDate();

        RuleFor(x => x.CreditLimit)
            .Null().When(x => x.Type != AccountType.CreditCard)
            .WithErrorCode("credit_limit_not_allowed").WithMessage("Credit limit is only allowed for credit cards.");
        RuleFor(x => x.CreditLimit).GreaterThanOrEqualTo(0).When(x => x.CreditLimit is not null);

        When(x => x.Type is not null && Account.SupportsInterest(x.Type.Value), () =>
        {
            RuleFor(x => x.InterestRatePercent).InclusiveBetween(0m, 100m);
            RuleFor(x => x.CapitalizationPeriod).NotNull().IsInEnum()
                .When(x => x.InterestRatePercent is not null)
                .WithMessage("Capitalization period is required when an interest rate is set.");
            RuleFor(x => x.OpenDate).NotNull()
                .When(x => x.Type == AccountType.Deposit || x.InterestRatePercent is not null)
                .WithMessage("Open date is required for deposits and interest-bearing savings.");
            RuleFor(x => x.MaturityDate)
                .GreaterThan(x => x.OpenDate)
                .When(x => x.MaturityDate is not null && x.OpenDate is not null)
                .WithMessage("Maturity date must be after the open date.");
        }).Otherwise(() =>
        {
            RuleFor(x => x.InterestRatePercent).Null().WithErrorCode("interest_not_allowed")
                .WithMessage("Interest settings are only allowed for deposits and savings.");
            RuleFor(x => x.CapitalizationPeriod).Null().WithErrorCode("interest_not_allowed")
                .WithMessage("Interest settings are only allowed for deposits and savings.");
            RuleFor(x => x.MaturityDate).Null().WithErrorCode("interest_not_allowed")
                .WithMessage("Maturity date is only allowed for deposits and savings.");
        });
    }
}
