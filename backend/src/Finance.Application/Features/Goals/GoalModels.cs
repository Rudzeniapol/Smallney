using Finance.Application.Common;
using Finance.Domain.Goals;
using FluentValidation;

namespace Finance.Application.Features.Goals;

public record SavingsGoalPayload
{
    public string? Name { get; init; }

    /// <summary>Minor units of <see cref="Currency"/>.</summary>
    public long TargetAmount { get; init; }

    public string? Currency { get; init; }

    public DateOnly? TargetDate { get; init; }

    /// <summary>When set, progress is this account's balance; otherwise the sum of transfers marked with the goal.</summary>
    public Guid? LinkedAccountId { get; init; }

    public int Priority { get; init; }

    public bool IsCompleted { get; init; }

    /// <summary>Defaults to today when IsCompleted is set without a date.</summary>
    public DateOnly? CompletedOn { get; init; }

    public string? Color { get; init; }

    public string? Icon { get; init; }
}

public sealed record CreateSavingsGoalRequest : SavingsGoalPayload
{
    /// <summary>Client-generated UUID v7. Generated by the server when omitted.</summary>
    public Guid? Id { get; init; }
}

public sealed record SavingsGoalResponse(
    Guid Id,
    string Name,
    long TargetAmount,
    string Currency,
    DateOnly? TargetDate,
    Guid? LinkedAccountId,
    int Priority,
    bool IsCompleted,
    DateOnly? CompletedOn,
    string? Color,
    string? Icon,
    GoalProgressResponse Progress,
    long Version,
    DateTime CreatedAt,
    DateTime UpdatedAt)
{
    public static SavingsGoalResponse From(SavingsGoal g, GoalProgress p) => new(
        g.Id, g.Name, g.TargetAmount, g.Currency, g.TargetDate, g.LinkedAccountId, g.Priority, g.IsCompleted, g.CompletedOn,
        g.Color, g.Icon, GoalProgressResponse.From(p), g.Version, g.CreatedAt, g.UpdatedAt);
}

/// <param name="Current">Saved so far, minor units of the goal currency.</param>
/// <param name="MonthsLeft">Monthly contributions left before the target date (null without a date).</param>
/// <param name="RecommendedMonthly">(Target − Current) / MonthsLeft, rounded up (null without a date).</param>
public sealed record GoalProgressResponse(
    long Current,
    long Remaining,
    decimal Percent,
    int? MonthsLeft,
    long? RecommendedMonthly,
    bool IsOverdue)
{
    public static GoalProgressResponse From(GoalProgress p) =>
        new(p.Current, p.Remaining, p.Percent, p.MonthsLeft, p.RecommendedMonthly, p.IsOverdue);
}

internal sealed class SavingsGoalPayloadValidator : AbstractValidator<SavingsGoalPayload>
{
    public SavingsGoalPayloadValidator()
    {
        RuleFor(x => x.Name).NotEmpty().MaximumLength(100);
        RuleFor(x => x.TargetAmount).GreaterThan(0);
        RuleFor(x => x.Currency).NotEmpty().IsCurrencyCode();
        RuleFor(x => x.TargetDate).IsSaneDate();
        RuleFor(x => x.CompletedOn).IsSaneDate();
        RuleFor(x => x.Color).IsHexColor();
        RuleFor(x => x.Icon).MaximumLength(50);
    }
}
