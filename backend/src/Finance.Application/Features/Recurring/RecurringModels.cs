using Finance.Application.Common;
using Finance.Domain.Recurring;
using Finance.Domain.Transactions;
using FluentValidation;

namespace Finance.Application.Features.Recurring;

public record RecurringRulePayload : ITransactionTemplate
{
    public string? Name { get; init; }

    public Guid? AccountId { get; init; }

    public TransactionType? Type { get; init; }

    public long Amount { get; init; }

    public Guid? CategoryId { get; init; }

    public string? Note { get; init; }

    public IReadOnlyList<string>? Tags { get; init; }

    public Guid? ToAccountId { get; init; }

    public long? ToAmount { get; init; }

    public Guid? SavingsGoalId { get; init; }

    public Frequency? Frequency { get; init; }

    /// <summary>Every N days/weeks/months/years. Defaults to 1.</summary>
    public int? Interval { get; init; }

    /// <summary>Monthly/Yearly: 1–31, defaults to StartDate's day; past the month end means the last day.</summary>
    public int? DayOfMonth { get; init; }

    /// <summary>Weekly: defaults to StartDate's weekday.</summary>
    public DayOfWeek? DayOfWeek { get; init; }

    public DateOnly? StartDate { get; init; }

    public DateOnly? EndDate { get; init; }

    public bool IsActive { get; init; } = true;
}

public sealed record CreateRecurringRuleRequest : RecurringRulePayload
{
    /// <summary>Client-generated UUID v7. Generated by the server when omitted.</summary>
    public Guid? Id { get; init; }
}

public sealed record RecurringRuleResponse(
    Guid Id,
    string Name,
    Guid AccountId,
    TransactionType Type,
    long Amount,
    Guid? CategoryId,
    string? Note,
    IReadOnlyList<string> Tags,
    Guid? ToAccountId,
    long? ToAmount,
    Guid? SavingsGoalId,
    Frequency Frequency,
    int Interval,
    int? DayOfMonth,
    DayOfWeek? DayOfWeek,
    DateOnly StartDate,
    DateOnly? EndDate,
    bool IsActive,
    DateOnly? NextOccurrence,
    long Version,
    DateTime CreatedAt,
    DateTime UpdatedAt)
{
    public static RecurringRuleResponse From(RecurringRule r, DateOnly today) => new(
        r.Id, r.Name, r.AccountId, r.Type, r.Amount, r.CategoryId, r.Note, r.Tags, r.ToAccountId, r.ToAmount, r.SavingsGoalId,
        r.Frequency, r.Interval, r.DayOfMonth, r.DayOfWeek, r.StartDate, r.EndDate, r.IsActive,
        r.IsActive ? r.Schedule.NextOccurrence(today) : null,
        r.Version, r.CreatedAt, r.UpdatedAt);
}

public enum OccurrenceState
{
    /// <summary>Not materialized yet (future, or before the rule existed).</summary>
    Upcoming,
    Planned,
    Cleared,
    Skipped,
}

/// <summary>One occurrence of a rule, merged with its materialized transaction if there is one.</summary>
public sealed record OccurrenceResponse(
    Guid RuleId,
    string Name,
    DateOnly Date,
    TransactionType Type,
    long Amount,
    Guid AccountId,
    Guid? CategoryId,
    Guid TransactionId,
    OccurrenceState State);

internal sealed class RecurringRulePayloadValidator : AbstractValidator<RecurringRulePayload>
{
    public RecurringRulePayloadValidator()
    {
        Include(new TransactionTemplateValidator<RecurringRulePayload>());
        RuleFor(x => x.Name).NotEmpty().MaximumLength(100);
        RuleFor(x => x.Frequency).NotNull().IsInEnum();
        RuleFor(x => x.Interval).InclusiveBetween(1, RecurrenceSchedule.MaxInterval);
        RuleFor(x => x.StartDate).NotNull().IsSaneDate();
        RuleFor(x => x.EndDate).IsSaneDate()
            .GreaterThanOrEqualTo(x => x.StartDate).When(x => x.EndDate is not null && x.StartDate is not null);
        RuleFor(x => x.DayOfMonth).InclusiveBetween(1, 31);
        RuleFor(x => x.DayOfMonth).Null()
            .When(x => x.Frequency is not (Domain.Recurring.Frequency.Monthly or Domain.Recurring.Frequency.Yearly))
            .WithErrorCode("day_of_month_not_allowed").WithMessage("dayOfMonth is only used by monthly and yearly rules.");
        RuleFor(x => x.DayOfWeek).IsInEnum();
        RuleFor(x => x.DayOfWeek).Null()
            .When(x => x.Frequency != Domain.Recurring.Frequency.Weekly)
            .WithErrorCode("day_of_week_not_allowed").WithMessage("dayOfWeek is only used by weekly rules.");
    }
}

